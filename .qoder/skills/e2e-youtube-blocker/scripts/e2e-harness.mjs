#!/usr/bin/env node
/* Builds a disposable browser-extension copy with a test-only bridge page.
   The production extension/ and dist-chrome/ trees are never modified. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SKILL_DIR = path.resolve(SCRIPT_DIR, '..');
const ROOT = path.resolve(SKILL_DIR, '../../..');
const ASSETS = path.join(SKILL_DIR, 'assets');
const FF_ID = 'youtube-blocker-e2e@local.dev';
const BRIDGE = 'e2e-bridge.html';

const argv = process.argv.slice(2);
const cmd = argv[0];
const opt = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] !== undefined ? argv[i + 1] : fallback;
};
const flag = name => argv.includes(name);
const die = msg => { console.error(`ERROR: ${msg}`); process.exit(2); };
const print = obj => console.log(JSON.stringify(obj, null, 2));
const stamp = () => {
  const d = new Date();
  const p = n => String(n).padStart(2, '0');
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
};
const normalizeBrowser = b => (b === 'ff' ? 'firefox' : b);

function copyTree(src, dest) {
  if (!fs.existsSync(path.join(src, 'manifest.json'))) die(`no manifest.json in ${src}`);
  if (fs.existsSync(dest) && fs.readdirSync(dest).length) die(`refusing to overwrite non-empty ${dest}`);
  fs.mkdirSync(dest, { recursive: true });
  if (process.platform === 'darwin') {
    try {
      execFileSync('cp', ['-Rc', src + '/.', dest], { stdio: 'ignore' });
      return;
    } catch { /* fall through to a portable copy */ }
  }
  fs.cpSync(src, dest, { recursive: true });
}

function applyManifest(dest, browser) {
  const file = path.join(dest, 'manifest.json');
  const m = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (browser === 'firefox') {
    if (m.manifest_version !== 2) die('Firefox harness expects an MV2 manifest');
    m.browser_specific_settings = m.browser_specific_settings || {};
    m.browser_specific_settings.gecko = m.browser_specific_settings.gecko || {};
    m.browser_specific_settings.gecko.id = FF_ID;
    m.web_accessible_resources = ['popup/popup.html', BRIDGE];
  } else {
    if (m.manifest_version !== 3) die('Chrome harness expects an MV3 manifest');
    m.web_accessible_resources = [{
      resources: [BRIDGE, 'popup/popup.html'],
      matches: ['*://*.youtube.com/*', '*://*.music.youtube.com/*']
    }];
  }
  fs.writeFileSync(file, JSON.stringify(m, null, 2) + '\n');
  return m;
}

function installBridge(dest, browser) {
  for (const name of [BRIDGE, 'e2e-bridge.js']) {
    const from = path.join(ASSETS, name);
    if (!fs.existsSync(from)) die(`missing skill asset ${from}`);
    fs.copyFileSync(from, path.join(dest, name));
  }
  const leanNote = browser === 'firefox' ? 'Firefox' : 'Chrome';
  fs.writeFileSync(path.join(dest, 'E2E-README.txt'),
    `Test-only copy generated by .qoder/skills/e2e-youtube-blocker (${leanNote}).\n` +
    'The bridge page writes settings/keywords and publishes results into #yb-e2e-result.\n');
}

function prepare() {
  const browser = normalizeBrowser(opt('--browser', 'firefox'));
  if (!['firefox', 'chrome'].includes(browser)) die('--browser must be firefox|ff|chrome');
  const lean = flag('--lean');
  const runDir = path.resolve(opt('--run-dir', path.join(os.tmpdir(), `yb-e2e-${stamp()}`)));
  const srcDefault = browser === 'chrome' ? 'dist-chrome' : 'extension';
  const src = path.resolve(ROOT, opt('--source', srcDefault));
  const dest = path.resolve(opt('--out', path.join(runDir, browser === 'chrome' ? 'chrome-ext' : 'ff-ext')));

  fs.mkdirSync(runDir, { recursive: true });
  copyTree(src, dest);

  for (const rel of ['devreport.js', '.DS_Store']) {
    fs.rmSync(path.join(dest, rel), { recursive: true, force: true });
  }
  if (lean) {
    fs.rmSync(path.join(dest, 'models'), { recursive: true, force: true });
    const lib = path.join(dest, 'lib');
    if (fs.existsSync(lib)) {
      for (const name of fs.readdirSync(lib)) {
        if (name !== 'whisper.js') fs.rmSync(path.join(lib, name), { recursive: true, force: true });
      }
    }
  }

  const manifest = applyManifest(dest, browser);
  installBridge(dest, browser);

  const result = {
    browser,
    runDir,
    extDir: dest,
    extensionId: browser === 'firefox' ? FF_ID : null,
    manifestVersion: manifest.manifest_version,
    version: manifest.version,
    lean,
    bridgePage: BRIDGE,
    note: browser === 'firefox'
      ? 'Install extDir as a temporary add-on, then run: e2e-harness.mjs url --browser ff --profile <profile> --id ' + FF_ID
      : 'Install extDir, read the extension id, then run: e2e-harness.mjs url --browser chrome --id <id>'
  };
  fs.writeFileSync(path.join(runDir, 'harness.json'), JSON.stringify(result, null, 2) + '\n');
  print(result);
}

function findPrefs(profile) {
  const direct = path.join(profile, 'prefs.js');
  if (fs.existsSync(direct)) return direct;
  const nested = path.join(profile, 'firefox_devtools_mcp_profile', 'prefs.js');
  if (fs.existsSync(nested)) return nested;
  if (fs.existsSync(profile)) {
    for (const entry of fs.readdirSync(profile, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const candidate = path.join(profile, entry.name, 'prefs.js');
      if (fs.existsSync(candidate)) return candidate;
    }
  }
  return null;
}

function readUuid(prefsPath, id) {
  const text = fs.readFileSync(prefsPath, 'utf8');
  const line = text.split('\n').find(l => l.includes('extensions.webextensions.uuids'));
  if (!line) return null;
  const match = line.match(/user_pref\("extensions\.webextensions\.uuids",\s*"(.*)"\);/);
  if (!match) return null;
  const raw = match[1].replace(/\\"/g, '"').replace(/\\\\/g, '\\');
  try {
    return JSON.parse(raw)[id] || null;
  } catch {
    const escaped = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const fallback = raw.match(new RegExp(`"${escaped}"\\s*:\\s*"([0-9a-f-]+)"`));
    return fallback ? fallback[1] : null;
  }
}

async function waitForUuid(prefsPath, id, timeoutMs) {
  const started = Date.now();
  while (Date.now() - started <= timeoutMs) {
    const uuid = readUuid(prefsPath, id);
    if (uuid) return { uuid, waitedMs: Date.now() - started };
    await new Promise(r => setTimeout(r, 250));
  }
  return { uuid: null, waitedMs: Date.now() - started };
}

async function extensionUrl() {
  const browser = normalizeBrowser(opt('--browser', 'firefox'));
  if (browser === 'chrome') {
    const id = opt('--id');
    if (!id) die('--id <chrome-extension-id> is required for Chrome');
    const baseUrl = `chrome-extension://${id}/`;
    print({
      browser,
      extensionId: id,
      baseUrl,
      bridgeUrl: baseUrl + BRIDGE,
      popupUrl: baseUrl + 'popup/popup.html',
      bridge: 'direct navigation is allowed in Chrome; if not, open bridgeUrl from a YouTube page'
    });
    return;
  }

  const profile = opt('--profile');
  if (!profile) die('--profile <path from get_firefox_info> is required for Firefox');
  const id = opt('--id', FF_ID);
  const prefsPath = findPrefs(path.resolve(profile));
  if (!prefsPath) die(`prefs.js not found under ${profile}; use the Profile path from get_firefox_info`);
  const waitSec = Number(opt('--wait', '15'));
  const { uuid, waitedMs } = await waitForUuid(prefsPath, id, Math.max(0, waitSec) * 1000);
  if (!uuid) die(`UUID for ${id} not found in ${prefsPath} after ${waitSec}s; confirm install_extension succeeded`);
  const baseUrl = `moz-extension://${uuid}/`;
  print({
    browser: 'firefox',
    extensionId: id,
    uuid,
    baseUrl,
    bridgeUrl: baseUrl + BRIDGE,
    popupUrl: baseUrl + 'popup/popup.html',
    prefsPath,
    waitedMs
  });
}

function bridgeUrl() {
  const rawBase = opt('--base');
  if (!rawBase) die('--base <baseUrl from the url command> is required');
  const base = rawBase.replace(/\/e2e-bridge\.html.*$/, '').replace(/\/$/, '');
  const op = opt('--op', 'config');
  let payload = null;
  if (op === 'config') {
    const file = opt('--file');
    if (!file) die('--file <config.json> is required for op=config');
    const cfg = JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));
    payload = Buffer.from(JSON.stringify({
      settings: cfg.settings || {},
      keywords: cfg.keywords || []
    }), 'utf8').toString('base64url');
  }
  const query = `op=${encodeURIComponent(op)}${payload ? '&payload=' + payload : ''}`;
  print({ op, payload, url: `${base}/${BRIDGE}?${query}` });
}

function cleanup() {
  const raw = opt('--dir');
  if (!raw) die('--dir <temp run directory> is required');
  const dir = path.resolve(raw);
  const roots = [os.tmpdir(), '/tmp', '/private/tmp'].map(p => path.resolve(p));
  const underTmp = roots.some(root => dir === root || dir.startsWith(root + path.sep));
  if (!underTmp || !path.basename(dir).includes('yb-e2e')) {
    die(`refusing to remove ${dir}; only temp paths whose name contains "yb-e2e" are allowed`);
  }
  fs.rmSync(dir, { recursive: true, force: true });
  print({ removed: dir });
}

function usage() {
  console.log(`Usage:
  node e2e-harness.mjs prepare --browser firefox|chrome [--run-dir <dir>] [--lean]
  node e2e-harness.mjs url --browser firefox --profile <profile> [--id ${FF_ID}] [--wait 15]
  node e2e-harness.mjs url --browser chrome --id <extension-id>
  node e2e-harness.mjs bridge --base <baseUrl> --op config --file <config.json>
  node e2e-harness.mjs bridge --base <baseUrl> --op read|reset|ping
  node e2e-harness.mjs cleanup --dir <run-dir>`);
}

if (cmd === 'prepare') prepare();
else if (cmd === 'url') await extensionUrl();
else if (cmd === 'bridge') bridgeUrl();
else if (cmd === 'cleanup') cleanup();
else usage();
